using ClearFolder;
using ClearFolder.Models;
using ClearFolder.Services;
using Moq;

namespace TestApp;

[TestClass]
public class MainWindowViewModelTests
{
    [TestMethod]
    public void ClearFolderCommand_WhenNoFilesAreMarkedForDeletion_ShouldBeDisabled()
    {
        // Arrange
        Mock<IDialogService> mockDialog = new Mock<IDialogService>();
        Mock<IFolderCleaner> mockCleaner = new Mock<IFolderCleaner>();
        Mock<IFolderRepository> mockRepo = new Mock<IFolderRepository>();
        Mock<IRecycleBinService> mockBin = new Mock<IRecycleBinService>();
        MainWindowViewModel viewModel =
            new MainWindowViewModel(mockDialog.Object, mockCleaner.Object, mockRepo.Object, mockBin.Object)
            {
                Folders = [new Folder { Name = @"C:\Test", DeleteFilesCount = 0 }]
            };

        // Act
        // Accessing the relay command generated by CommunityToolkit.Mvvm
        viewModel.SetClearButtonEnabled();
        // Assert
        Assert.IsFalse(viewModel.ClearButtonEnabled,
            "The Clear Folder button should be disabled when there are zero files to delete.");
    }
}